# Garantir que a tabela 'Padrão Loja' existe
existentes = {r[0]: r[1] for r in con.execute('SELECT codigo, id FROM produtos').fetchall()}
criados = 0
for codigo, descricao, preco in PRODUTOS:
    if codigo not in existentes:
        cur = con.execute('INSERT INTO produtos (codigo, descricao) VALUES (?, ?)', (codigo, descricao[:200]))
        existentes[codigo] = cur.lastrowid
        criados += 1
con.commit()
print(f'Produtos criados: {criados}')

tabela = con.execute("SELECT id FROM tabelas_precos WHERE nome='Padrão Loja'").fetchone()
if not tabela:
    cur = con.execute("INSERT INTO tabelas_precos (nome, ativa) VALUES ('Padrão Loja', 1)")
    tabela_id = cur.lastrowid
    print(f'Tabela Padrão Loja criada id={tabela_id}')
else:
    tabela_id = tabela['id']
    print(f'Tabela Padrão Loja já existe id={tabela_id}')

inseridos = 0
for codigo, descricao, preco in PRODUTOS:
    pid = existentes.get(codigo)
    if pid:
        ex = con.execute('SELECT id FROM itens_tabela_precos WHERE tabela_id=? AND produto_id=?', (tabela_id, pid)).fetchone()
        if not ex:
            con.execute('INSERT INTO itens_tabela_precos (tabela_id, produto_id, preco_unitario) VALUES (?,?,?)', (tabela_id, pid, preco))
            inseridos += 1
        else:
            con.execute('UPDATE itens_tabela_precos SET preco_unitario=? WHERE tabela_id=? AND produto_id=?', (preco, tabela_id, pid))
con.commit()
print(f'Preços inseridos/atualizados: {inseridos}')
total = con.execute('SELECT COUNT(*) FROM itens_tabela_precos WHERE tabela_id=?', (tabela_id,)).fetchone()[0]
print(f'Total final: {total} itens na Padrão Loja')
